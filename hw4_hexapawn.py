# ตัวเล่นของ AI
# ============================================================
def ai_player(game, state):

    move = alpha_beta_search(
        state,
        game
    )

    print(
        f'AI เลือกเดินจาก '
        f'{move[0]} ไป {move[1]}'
    )

    return move


