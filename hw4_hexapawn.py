def start_game(game, white, black):

    state = game.initial

    players = {
        'W': white,
        'B': black
    }

    round_no = 1

    while True:

        print(
            f'\n---------- รอบที่ {round_no} ----------'
        )

        game.display(state)

        if game.terminal_test(state):

            if state.score == 1:
                print('White เป็นฝ่ายชนะ')

            elif state.score == -1:
                print('Black เป็นฝ่ายชนะ')

            else:
                print('เกมจบแบบเสมอ')

            return state.score

        current = game.to_move(state)

        if current == 'W':
            print('ถึงตาของผู้เล่นฝ่าย White')
        else:
            print('ถึงตาของ AI ฝ่าย Black')

        move = players[current](
            game,
            state
        )

        state = game.result(
            state,
            move
        )

        round_no += 1


