# ค้นหาตาเดินที่ดีที่สุดด้วย Alpha-Beta Pruning
# ============================================================
def alpha_beta_search(state, game):

    root_player = game.to_move(state)

    def maximize(state, alpha, beta):

        if game.terminal_test(state):
            return game.utility(
                state,
                root_player
            )

        value = -INF

        for move in game.actions(state):

            next_state = game.result(
                state,
                move
            )

            value = max(
                value,
                minimize(
                    next_state,
                    alpha,
                    beta
                )
            )

            if value >= beta:
                return value

            alpha = max(
                alpha,
                value
            )

        return value

    def minimize(state, alpha, beta):

        if game.terminal_test(state):
            return game.utility(
                state,
                root_player
            )

        value = INF

        for move in game.actions(state):

            next_state = game.result(
                state,
                move
            )

            value = min(
                value,
                maximize(
                    next_state,
                    alpha,
                    beta
                )
            )

            if value <= alpha:
                return value

            beta = min(
                beta,
                value
            )

        return value

    best_value = -INF
    selected_move = None

    for move in game.actions(state):

        value = minimize(
            game.result(state, move),
            best_value,
            INF
        )

        if value > best_value:
            best_value = value
            selected_move = move

    return selected_move


