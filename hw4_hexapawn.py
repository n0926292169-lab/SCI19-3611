from collections import namedtuple
import random

# ============================================================
# ใช้เก็บข้อมูลสถานะปัจจุบันของเกม
# ============================================================
State = namedtuple(
    'State',
    ['turn', 'score', 'pieces', 'legal_moves', 'finished']
)

INF = float('inf')


# ============================================================
# คลาสพื้นฐานสำหรับเกมแบบค้นหาสถานะ
# ============================================================
class GameBase:

    def actions(self, state):
        raise NotImplementedError

    def result(self, state, move):
        raise NotImplementedError

    def utility(self, state, player):
        raise NotImplementedError

    def terminal_test(self, state):
        return not self.actions(state)

    def to_move(self, state):
        return state.turn

    def display(self, state):
        print(state)


# ============================================================
# เกม Hexapawn
# ============================================================
class Hexapawn(GameBase):

    def __init__(self, rows=3, cols=3):
        self.rows = rows
        self.cols = cols

        pieces = {}

        # วางตัวหมากฝ่ายดำไว้ด้านบน
        for col in range(cols):
            pieces[(col, 0)] = 'B'

        # วางตัวหมากฝ่ายขาวไว้ด้านล่าง
        for col in range(cols):
            pieces[(col, rows - 1)] = 'W'

        first_moves = self.find_moves(pieces, 'W')

        self.initial = State(
            turn='W',
            score=0,
            pieces=pieces,
            legal_moves=first_moves,
            finished=False
        )

    def find_moves(self, pieces, player):

        possible = []

        step = -1 if player == 'W' else 1
        enemy = 'B' if player == 'W' else 'W'

        for (col, row), piece in pieces.items():

            if piece != player:
                continue

            next_row = row + step

            if not (0 <= next_row < self.rows):
                continue

            # เดินตรงได้เมื่อช่องข้างหน้าว่าง
            if (col, next_row) not in pieces:
                possible.append(
                    ((col, row), (col, next_row))
                )

            # กินหมากฝ่ายตรงข้ามในแนวทแยง
            for offset in (-1, 1):

                next_col = col + offset

                if (
                    0 <= next_col < self.cols
                    and pieces.get((next_col, next_row)) == enemy
                ):
                    possible.append(
                        ((col, row), (next_col, next_row))
                    )

        return possible

    def actions(self, state):
        return state.legal_moves

    def result(self, state, move):

        start, end = move
        player = state.turn

        pieces = dict(state.pieces)

        # ย้ายตัวหมากออกจากตำแหน่งเก่า
        del pieces[start]

        # วางไว้ที่ตำแหน่งใหม่
        pieces[end] = player

        enemy = 'B' if player == 'W' else 'W'

        enemy_moves = self.find_moves(
            pieces,
            enemy
        )

        finished, score = self.check_result(
            pieces,
            end,
            player,
            enemy_moves
        )

        return State(
            turn=enemy,
            score=score,
            pieces=pieces,
            legal_moves=enemy_moves,
            finished=finished
        )

    def check_result(
        self,
        pieces,
        destination,
        player,
        enemy_moves
    ):

        col, row = destination
        enemy = 'B' if player == 'W' else 'W'

        # ฝ่ายขาวไปถึงด้านบน
        if player == 'W' and row == 0:
            return True, 1

        # ฝ่ายดำไปถึงด้านล่าง
        if player == 'B' and row == self.rows - 1:
            return True, -1

        # ฝ่ายตรงข้ามไม่มีหมากเหลือ
        if not any(
            piece == enemy
            for piece in pieces.values()
        ):
            return True, 0

        # ฝ่ายตรงข้ามไม่สามารถเดินต่อได้
        if not enemy_moves:
            return True, 0

        return False, 0

    def utility(self, state, player):

        if player == 'W':
            return state.score

        return -state.score

    def terminal_test(self, state):
        return state.finished

    def display(self, state):

        print(
            '    ' +
            '   '.join(
                str(i)
                for i in range(self.cols)
            )
        )

        print('  +' + '---+' * self.cols)

        for row in range(self.rows):

            line = []

            for col in range(self.cols):
                line.append(
                    state.pieces.get(
                        (col, row),
                        '.'
                    )
                )

            print(
                f'{row} | ' +
                ' | '.join(line) +
                ' |'
            )

            print(
                '  +' +
                '---+' * self.cols
            )

        print()


